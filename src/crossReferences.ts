/**
 * Returns cross-references for a given verse.
 * Returns null if no cross-references exist.
 */
export function getCrossReferences(bookId: string, chapter: number, verse: number): string[] | null {
  const key = `${bookId}:${chapter}:${verse}`;
  return CROSS_REFS[key] || null;
}

/**
 * Parses a reference string like "JHN:3:16" into { bookId, chapter, verse }.
 */
export function parseCrossRef(ref: string): { bookId: string; chapter: number; verse: number } | null {
  const parts = ref.split(':');
  if (parts.length !== 3) return null;
  const [bookId, ch, v] = parts;
  return { bookId, chapter: parseInt(ch, 10), verse: parseInt(v, 10) };
}

